#!/usr/bin/env node
/**
 * Gen soft golden dragon-spirit sheets (NOT pixel Nineball 100px).
 * Pure Node PNG — no Playwright.
 *
 * Usage: node scripts/gen-dragon-spirit-fx.mjs
 * Out:   assets/fx/dragon_spirit/spirit_01.png … spirit_08.png
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { deflateSync } from "node:zlib";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "assets/fx/dragon_spirit");
const SIZE = 256;
const FRAMES = 8;

function crc32(buf) {
  let c = ~0;
  for (let i = 0; i < buf.length; i++) {
    c ^= buf[i];
    for (let k = 0; k < 8; k++) c = c & 1 ? (0xedb88320 ^ (c >>> 1)) : c >>> 1;
  }
  return ~c >>> 0;
}

function chunk(type, data) {
  const typeBuf = Buffer.from(type);
  const len = Buffer.alloc(4);
  len.writeUInt32BE(data.length);
  const crcBuf = Buffer.concat([typeBuf, data]);
  const crc = Buffer.alloc(4);
  crc.writeUInt32BE(crc32(crcBuf));
  return Buffer.concat([len, typeBuf, data, crc]);
}

function encodePng(rgba, w, h) {
  const raw = Buffer.alloc((w * 4 + 1) * h);
  for (let y = 0; y < h; y++) {
    const row = y * (w * 4 + 1);
    raw[row] = 0;
    rgba.copy(raw, row + 1, y * w * 4, (y + 1) * w * 4);
  }
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(w, 0);
  ihdr.writeUInt32BE(h, 4);
  ihdr[8] = 8;
  ihdr[9] = 6;
  ihdr[10] = 0;
  ihdr[11] = 0;
  ihdr[12] = 0;
  return Buffer.concat([
    Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]),
    chunk("IHDR", ihdr),
    chunk("IDAT", deflateSync(raw, { level: 9 })),
    chunk("IEND", Buffer.alloc(0)),
  ]);
}

function setPx(buf, w, x, y, r, g, b, a) {
  const xi = Math.round(x);
  const yi = Math.round(y);
  if (xi < 0 || yi < 0 || xi >= w || yi >= w) return;
  const i = (yi * w + xi) * 4;
  // alpha blend over
  const oa = buf[i + 3] / 255;
  const na = a / 255;
  const outA = na + oa * (1 - na);
  if (outA <= 0) return;
  buf[i] = Math.min(255, (r * na + buf[i] * oa * (1 - na)) / outA);
  buf[i + 1] = Math.min(255, (g * na + buf[i + 1] * oa * (1 - na)) / outA);
  buf[i + 2] = Math.min(255, (b * na + buf[i + 2] * oa * (1 - na)) / outA);
  buf[i + 3] = Math.min(255, outA * 255);
}

function stampGlow(buf, w, cx, cy, radius, r, g, b, peakA) {
  const r2 = radius * radius;
  const x0 = Math.max(0, Math.floor(cx - radius));
  const x1 = Math.min(w - 1, Math.ceil(cx + radius));
  const y0 = Math.max(0, Math.floor(cy - radius));
  const y1 = Math.min(w - 1, Math.ceil(cy + radius));
  for (let y = y0; y <= y1; y++) {
    for (let x = x0; x <= x1; x++) {
      const dx = x - cx;
      const dy = y - cy;
      const d2 = dx * dx + dy * dy;
      if (d2 > r2) continue;
      const t = Math.sqrt(d2) / radius;
      // soft falloff
      let a = peakA;
      if (t < 0.25) a *= 1;
      else if (t < 0.55) a *= 1 - (t - 0.25) / 0.3 * 0.35;
      else a *= Math.max(0, (1 - t) / 0.45) * 0.65;
      if (a <= 0.004) continue;
      setPx(buf, w, x, y, r, g, b, a * 255);
    }
  }
}

function renderFrame(fi) {
  const w = SIZE;
  const buf = Buffer.alloc(w * w * 4);
  const phase = (fi / FRAMES) * Math.PI * 2;
  const cx = w * 0.52;
  const cy = w * 0.48;

  for (let i = 0; i < 18; i++) {
    const t = i / 17;
    const x = cx - t * w * 0.55 + Math.sin(phase + t * 4.2) * w * 0.06;
    const y = cy + Math.sin(phase * 0.7 + t * 3.1) * w * 0.1 + (t - 0.3) * w * 0.08;
    const rad = w * (0.14 - t * 0.09);
    const peak = 0.95 - t * 0.55;
    stampGlow(buf, w, x, y, rad, 255, 200 - t * 60, 50 + t * 20, peak);
  }

  const hx = cx + w * 0.06;
  const hy = cy - w * 0.02;
  stampGlow(buf, w, hx, hy, w * 0.22, 255, 240, 180, 1);
  stampGlow(buf, w, hx, hy, w * 0.14, 255, 210, 90, 0.95);

  for (const [ox, oy] of [
    [-0.06, -0.12],
    [0.08, -0.14],
  ]) {
    stampGlow(buf, w, hx + ox * w, hy + oy * w, w * 0.08, 255, 230, 160, 0.9);
  }
  for (const ox of [-0.04, 0.05]) {
    stampGlow(buf, w, hx + ox * w, hy - w * 0.01, w * 0.028, 255, 255, 255, 1);
  }

  return encodePng(buf, w, w);
}

mkdirSync(OUT, { recursive: true });
for (let i = 0; i < FRAMES; i++) {
  const name = `spirit_${String(i + 1).padStart(2, "0")}.png`;
  writeFileSync(join(OUT, name), renderFrame(i));
  console.log("wrote", name);
}
writeFileSync(
  join(OUT, "README.md"),
  `# Dragon spirit (soft glow)\n\nGenerated by \`scripts/gen-dragon-spirit-fx.mjs\`.\nSoft additive silhouettes (${SIZE}px) — not pixel Nineball.\n`
);
console.log("Done →", OUT);
